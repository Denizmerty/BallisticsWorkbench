import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'prettier';

const schemaPath = 'protocol/ballistics-protocol.schema.json';
const cppPath = 'src/Ballistics.Cli/generated_protocol_structure.hpp';
const typeScriptPath = 'src/Ballistics.Desktop/shared/generatedProtocolStructure.ts';

function resolveReference(schema, node) {
    if (!node?.$ref) return node;
    if (!node.$ref.startsWith('#/')) throw new Error(`Unsupported external ref: ${node.$ref}`);
    return node.$ref
        .slice(2)
        .split('/')
        .reduce(
            (value, segment) => value[segment.replaceAll('~1', '/').replaceAll('~0', '~')],
            schema,
        );
}

function property(schema, node, name) {
    const resolved = resolveReference(schema, node);
    const value = resolved?.properties?.[name];
    if (!value) throw new Error(`Protocol schema is missing property ${name}.`);
    return resolveReference(schema, value);
}

function keys(schema, node) {
    const resolved = resolveReference(schema, node);
    if (!resolved?.properties) throw new Error('Protocol structure node has no properties.');
    return Object.keys(resolved.properties);
}

function structures(schema) {
    const calculation = schema.oneOf.find((entry) => entry.title === 'Calculation request');
    if (!calculation) throw new Error('Calculation request schema could not be found.');
    const calibration = schema.oneOf.find(
        (entry) => entry.title === 'Reference-BC calibration request',
    );
    if (!calibration) throw new Error('Calibration request schema could not be found.');
    const scenario = property(schema, calculation, 'scenario');
    const atmosphere = property(schema, scenario, 'atmosphere');
    const firearms = property(schema, scenario, 'firearms');
    return {
        calculationRoot: keys(schema, calculation),
        calibrationRoot: keys(schema, calibration),
        calibrationAtmosphere: keys(schema, property(schema, calibration, 'atmosphere')),
        calibrationProjectile: keys(schema, property(schema, calibration, 'projectile')),
        calibrationConstantFit: keys(schema, property(schema, calibration, 'fit').oneOf[0]),
        calibrationVelocityBandsFit: keys(schema, property(schema, calibration, 'fit').oneOf[1]),
        calibrationObservation: keys(schema, schema.$defs.calibrationObservation),
        scenario: keys(schema, scenario),
        geometry: keys(schema, property(schema, scenario, 'geometry')),
        atmosphere: keys(schema, atmosphere),
        windLayer: keys(schema, schema.$defs.windLayer),
        firearms: keys(schema, firearms),
        shotgun: keys(schema, schema.$defs.shotgun),
        rifle: keys(schema, schema.$defs.rifle),
        temperatureVelocityPoint: keys(schema, schema.$defs.temperatureVelocityPoint),
        uncertainty: keys(schema, schema.$defs.uncertaintyInput),
        uncertaintyCorrelation: keys(schema, schema.$defs.uncertaintyCorrelation),
        buckshotPattern: keys(schema, schema.$defs.buckshotPatternInput),
        buckshotTarget: keys(schema, schema.$defs.buckshotTarget),
        patternObservation: keys(schema, schema.$defs.patternObservation),
        customLoad: keys(schema, schema.$defs.customLoad),
        referenceBcDrag: keys(schema, schema.$defs.referenceBcDrag),
        tabulatedCdDrag: keys(schema, schema.$defs.tabulatedCdDrag),
        sphereDrag: keys(schema, schema.$defs.sphereDrag),
        machCdPoint: keys(schema, schema.$defs.machCdPoint),
        bcBand: keys(schema, schema.$defs.bcBand),
        bulletGeometry: ['lengthInches', 'diameterInches', 'twistInches'],
    };
}

function snakeCase(value) {
    return value.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function cppDocument(structure) {
    const arrays = Object.entries(structure)
        .map(([name, values]) => {
            const entries = values.map((value) => `    "${value}"`).join(',\n');
            return `inline constexpr std::array<std::string_view, ${values.length}> ${snakeCase(name)}_fields {\n${entries}\n};`;
        })
        .join('\n\n');
    return `#pragma once

// Generated by scripts/protocol/generate-protocol-structure.mjs from the protocol schema.
// Semantic and cross-field validation remains in protocol.cpp.

#include <array>
#include <string_view>

namespace ballistics::protocol::generated
{

${arrays}

} // namespace ballistics::protocol::generated
`;
}

function locateClangFormat() {
    for (const command of ['clang-format', 'clang-format.exe']) {
        const probe = spawnSync(command, ['--version'], { encoding: 'utf8', windowsHide: true });
        if (!probe.error && probe.status === 0) return command;
    }
    const programFiles = process.env['ProgramFiles(x86)'];
    if (programFiles) {
        const vswhere = path.join(
            programFiles,
            'Microsoft Visual Studio',
            'Installer',
            'vswhere.exe',
        );
        if (existsSync(vswhere)) {
            const installation = execFileSync(
                vswhere,
                ['-latest', '-products', '*', '-property', 'installationPath'],
                { encoding: 'utf8' },
            ).trim();
            const candidate = path.join(
                installation,
                'VC',
                'Tools',
                'Llvm',
                'x64',
                'bin',
                'clang-format.exe',
            );
            if (existsSync(candidate)) return candidate;
        }
    }
    throw new Error('clang-format is required to generate the native protocol structure.');
}

function formatCpp(source, repositoryRoot) {
    const result = spawnSync(locateClangFormat(), ['--style=file'], {
        cwd: repositoryRoot,
        input: source,
        encoding: 'utf8',
        windowsHide: true,
    });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`clang-format failed: ${result.stderr}`);
    return result.stdout;
}

async function typeScriptDocument(structure) {
    return format(
        `// Generated by scripts/protocol/generate-protocol-structure.mjs.
export const protocolStructure = ${JSON.stringify(structure, null, 4)} as const;
`,
        { parser: 'typescript', tabWidth: 4, printWidth: 100, singleQuote: true },
    );
}

export async function generateProtocolStructure(repositoryRoot, check = false) {
    const root = path.resolve(repositoryRoot);
    const schema = JSON.parse(await readFile(path.join(root, schemaPath), 'utf8'));
    const structure = structures(schema);
    const documents = [
        [cppPath, formatCpp(cppDocument(structure), root)],
        [typeScriptPath, await typeScriptDocument(structure)],
    ];
    const changed = [];
    for (const [relativePath, content] of documents) {
        const absolutePath = path.join(root, relativePath);
        const current = await readFile(absolutePath, 'utf8').catch(() => null);
        if (current === content) continue;
        changed.push(relativePath);
        if (!check) await writeFile(absolutePath, content, 'utf8');
    }
    if (check && changed.length) {
        throw new Error(`Generated protocol structure is stale: ${changed.join(', ')}.`);
    }
    return { changed, structure };
}

async function main() {
    const check = process.argv.includes('--check');
    const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
    const result = await generateProtocolStructure(root, check);
    process.stdout.write(
        result.changed.length
            ? `${check ? 'Stale' : 'Updated'} ${result.changed.join(', ')}.\n`
            : 'Generated protocol structure is current.\n',
    );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    await main();
}
