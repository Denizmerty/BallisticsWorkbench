import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'prettier';

const cppPath = 'src/Ballistics.Core/include/generated_atmosphere_conversions.hpp';
const typeScriptPath = 'src/Ballistics.Desktop/shared/generatedAtmosphereConversions.ts';

const constants = Object.freeze({
    referenceTemperatureK: 288.15,
    referencePressureHpa: 1013.25,
    lapseRateKM: 0.0065,
    gravityMps2: 9.80665,
    dryAirMolarMassKgMol: 0.0289644,
    universalGasConstantJMolk: 8.31447,
    dryAirGasConstantJKgk: 287.058,
    altimeterReferenceTemperatureK: 288,
    altimeterPressureExponent: 5.2561,
    minimumAltitudeM: -1000,
    maximumAltitudeM: 11000,
});

function locateClangFormat() {
    for (const command of ['clang-format', 'clang-format.exe']) {
        const probe = spawnSync(command, ['--version'], { encoding: 'utf8', windowsHide: true });
        if (!probe.error && probe.status === 0) return command;
    }
    const programFiles = process.env['ProgramFiles(x86)'];
    if (programFiles) {
        const vswhere = path.join(
            programFiles,
            'Microsoft Visual Studio',
            'Installer',
            'vswhere.exe',
        );
        if (existsSync(vswhere)) {
            const installation = execFileSync(
                vswhere,
                ['-latest', '-products', '*', '-property', 'installationPath'],
                { encoding: 'utf8' },
            ).trim();
            const candidate = path.join(
                installation,
                'VC',
                'Tools',
                'Llvm',
                'x64',
                'bin',
                'clang-format.exe',
            );
            if (existsSync(candidate)) return candidate;
        }
    }
    throw new Error('clang-format is required to generate atmosphere conversions.');
}

function formatCpp(source, repositoryRoot) {
    const result = spawnSync(locateClangFormat(), ['--style=file'], {
        cwd: repositoryRoot,
        input: source,
        encoding: 'utf8',
        windowsHide: true,
    });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`clang-format failed: ${result.stderr}`);
    return result.stdout;
}

const cppNumber = (value) => (Number.isInteger(value) ? `${value}.0` : String(value));

function cppDocument() {
    const c = Object.fromEntries(
        Object.entries(constants).map(([name, value]) => [name, cppNumber(value)]),
    );
    return `#pragma once

// Generated by scripts/product/generate-atmosphere-conversions.mjs.
// The generator is the single formula owner for native and renderer atmosphere conversions.

#include <algorithm>
#include <cmath>

namespace ballistics::generated::atmosphere_conversion
{

inline constexpr double reference_temperature_k = ${c.referenceTemperatureK};
inline constexpr double reference_pressure_hpa = ${c.referencePressureHpa};
inline constexpr double lapse_rate_k_m = ${c.lapseRateKM};
inline constexpr double gravity_mps2 = ${c.gravityMps2};
inline constexpr double dry_air_molar_mass_kg_mol = ${c.dryAirMolarMassKgMol};
inline constexpr double universal_gas_constant_j_molk = ${c.universalGasConstantJMolk};
inline constexpr double dry_air_gas_constant_j_kgk = ${c.dryAirGasConstantJKgk};
inline constexpr double altimeter_reference_temperature_k = ${c.altimeterReferenceTemperatureK};
inline constexpr double altimeter_pressure_exponent = ${c.altimeterPressureExponent};
inline constexpr double minimum_altitude_m = ${c.minimumAltitudeM};
inline constexpr double maximum_altitude_m = ${c.maximumAltitudeM};
inline constexpr double pressure_exponent = gravity_mps2 * dry_air_molar_mass_kg_mol /
    (universal_gas_constant_j_molk * lapse_rate_k_m);
inline constexpr double reference_density_kg_m3 =
    reference_pressure_hpa * 100.0 / (dry_air_gas_constant_j_kgk * reference_temperature_k);

inline double clamp_altitude_m(double altitude_m)
{
    return std::clamp(altitude_m, minimum_altitude_m, maximum_altitude_m);
}

inline double altitude_to_pressure_hpa(double altitude_m)
{
    const auto height_m = clamp_altitude_m(altitude_m);
    return reference_pressure_hpa *
        std::pow(1.0 - lapse_rate_k_m * height_m / reference_temperature_k, pressure_exponent);
}

inline double pressure_to_altitude_m(double pressure_hpa)
{
    const auto pressure = std::clamp(
        pressure_hpa,
        altitude_to_pressure_hpa(maximum_altitude_m),
        altitude_to_pressure_hpa(minimum_altitude_m)
    );
    return reference_temperature_k / lapse_rate_k_m *
        (1.0 - std::pow(pressure / reference_pressure_hpa, 1.0 / pressure_exponent));
}

inline double altimeter_setting_to_station_pressure_hpa(
    double altimeter_setting_hpa,
    double geometric_altitude_m
)
{
    const auto temperature_ratio =
        (altimeter_reference_temperature_k - lapse_rate_k_m * clamp_altitude_m(geometric_altitude_m)) /
        altimeter_reference_temperature_k;
    return altimeter_setting_hpa * std::pow(temperature_ratio, altimeter_pressure_exponent);
}

inline double station_pressure_to_altimeter_setting_hpa(
    double station_pressure_hpa,
    double geometric_altitude_m
)
{
    const auto temperature_ratio =
        (altimeter_reference_temperature_k - lapse_rate_k_m * clamp_altitude_m(geometric_altitude_m)) /
        altimeter_reference_temperature_k;
    return station_pressure_hpa / std::pow(temperature_ratio, altimeter_pressure_exponent);
}

inline double density_to_altitude_m(double density_kg_m3)
{
    return reference_temperature_k / lapse_rate_k_m *
        (1.0 - std::pow(std::max(0.0, density_kg_m3) / reference_density_kg_m3,
                        1.0 / (pressure_exponent - 1.0)));
}

} // namespace ballistics::generated::atmosphere_conversion
`;
}

async function typeScriptDocument() {
    const c = constants;
    return format(
        `/* Generated by scripts/product/generate-atmosphere-conversions.mjs. */
const REFERENCE_TEMPERATURE_K = ${c.referenceTemperatureK};
const REFERENCE_PRESSURE_HPA = ${c.referencePressureHpa};
const LAPSE_RATE_K_M = ${c.lapseRateKM};
const PRESSURE_EXPONENT =
    (${c.gravityMps2} * ${c.dryAirMolarMassKgMol}) /
    (${c.universalGasConstantJMolk} * LAPSE_RATE_K_M);
const REFERENCE_DENSITY_KG_M3 =
    (REFERENCE_PRESSURE_HPA * 100) /
    (${c.dryAirGasConstantJKgk} * REFERENCE_TEMPERATURE_K);
const MINIMUM_ALTITUDE_M = ${c.minimumAltitudeM};
const MAXIMUM_ALTITUDE_M = ${c.maximumAltitudeM};
const ALTIMETER_REFERENCE_TEMPERATURE_K = ${c.altimeterReferenceTemperatureK};
const ALTIMETER_PRESSURE_EXPONENT = ${c.altimeterPressureExponent};

const clampAltitudeM = (altitudeM: number) =>
    Math.max(MINIMUM_ALTITUDE_M, Math.min(MAXIMUM_ALTITUDE_M, altitudeM));

export const altitudeToPressureHpa = (altitudeM: number) =>
    REFERENCE_PRESSURE_HPA *
    Math.pow(
        1 - (LAPSE_RATE_K_M * clampAltitudeM(altitudeM)) / REFERENCE_TEMPERATURE_K,
        PRESSURE_EXPONENT,
    );

export const pressureToAltitudeM = (pressureHpa: number) =>
    (REFERENCE_TEMPERATURE_K / LAPSE_RATE_K_M) *
    (1 -
        Math.pow(
            Math.max(
                altitudeToPressureHpa(MAXIMUM_ALTITUDE_M),
                Math.min(altitudeToPressureHpa(MINIMUM_ALTITUDE_M), pressureHpa),
            ) / REFERENCE_PRESSURE_HPA,
            1 / PRESSURE_EXPONENT,
        ));

export const altimeterSettingToStationPressureHpa = (
    altimeterSettingHpa: number,
    geometricAltitudeM: number,
) =>
    altimeterSettingHpa *
    Math.pow(
        (ALTIMETER_REFERENCE_TEMPERATURE_K -
            LAPSE_RATE_K_M * clampAltitudeM(geometricAltitudeM)) /
            ALTIMETER_REFERENCE_TEMPERATURE_K,
        ALTIMETER_PRESSURE_EXPONENT,
    );

export const stationPressureToAltimeterSettingHpa = (
    stationPressureHpa: number,
    geometricAltitudeM: number,
) =>
    stationPressureHpa /
    Math.pow(
        (ALTIMETER_REFERENCE_TEMPERATURE_K -
            LAPSE_RATE_K_M * clampAltitudeM(geometricAltitudeM)) /
            ALTIMETER_REFERENCE_TEMPERATURE_K,
        ALTIMETER_PRESSURE_EXPONENT,
    );

export const densityToAltitudeM = (densityKgM3: number) =>
    (REFERENCE_TEMPERATURE_K / LAPSE_RATE_K_M) *
    (1 -
        Math.pow(
            Math.max(0, densityKgM3) / REFERENCE_DENSITY_KG_M3,
            1 / (PRESSURE_EXPONENT - 1),
        ));
`,
        { parser: 'typescript', tabWidth: 4, printWidth: 100, singleQuote: true },
    );
}

export async function generateAtmosphereConversions(repositoryRoot, check = false) {
    const root = path.resolve(repositoryRoot);
    const documents = [
        [cppPath, formatCpp(cppDocument(), root)],
        [typeScriptPath, await typeScriptDocument()],
    ];
    const changed = [];
    for (const [relativePath, content] of documents) {
        const absolutePath = path.join(root, relativePath);
        const current = await readFile(absolutePath, 'utf8').catch(() => null);
        if (current === content) continue;
        changed.push(relativePath);
        if (!check) await writeFile(absolutePath, content, 'utf8');
    }
    if (check && changed.length) {
        throw new Error(`Generated atmosphere conversions are stale: ${changed.join(', ')}.`);
    }
    return { changed };
}

async function main() {
    const check = process.argv.includes('--check');
    const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
    const result = await generateAtmosphereConversions(root, check);
    process.stdout.write(
        result.changed.length
            ? `${check ? 'Stale' : 'Updated'} ${result.changed.join(', ')}.\n`
            : 'Generated atmosphere conversions are current.\n',
    );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    await main();
}
